/** Développe une session compacte en objet lisible. */
export function expandSession(timetable, session) {
  const [day, range, code, teachers, room, options = {}] = session
  const [startTime, endTime] = range.split('-')
  return {
    program: timetable.program,
    level: timetable.level,
    day,
    startTime,
    endTime,
    code,
    teachers: teachers || '',
    room: room || timetable.defaultRoom || '',
    type: options.type || 'CM',
    group: options.group || '',
    title: options.title || '',
    optional: Boolean(options.optional),
  }
}

/** Toutes les sessions développées, dans l'ordre des emplois du temps. */
export function allSessions() {
  return TIMETABLES.flatMap((timetable) => timetable.sessions.map((session) => expandSession(timetable, session)))
}
